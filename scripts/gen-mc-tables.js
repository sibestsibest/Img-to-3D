const fs = require('fs');
const html = fs.readFileSync(process.argv[2], 'utf8');
const grab = (start) => {
  const i = html.indexOf(start); const j = html.indexOf('};', i);
  return html.slice(html.indexOf('{', i) , j + 1);
};
const edge = grab('int edgeTable[256]').match(/0x[0-9a-f]+/gi).map(h => parseInt(h, 16));
const triRaw = grab('int triTable[256][16]');
const rows = [...triRaw.matchAll(/\{([-\d,\s]+)\}/g)].map(m => m[1].split(',').map(s => parseInt(s.trim(), 10)));
if (edge.length !== 256 || rows.length !== 256 || rows.some(r => r.length !== 16)) throw new Error(`bad parse ${edge.length} ${rows.length}`);
let out = '// <auto-generated>\n// Marching cubes lookup tables from Paul Bourke, "Polygonising a scalar field"\n// (https://paulbourke.net/geometry/polygonise/), generated by scripts/gen-mc-tables.js.\n// </auto-generated>\nnamespace ImageTo3D.Core.Geometry;\n\ninternal static class MarchingCubesTables\n{\n';
out += '    public static readonly int[] EdgeTable =\n    [\n';
for (let i = 0; i < 256; i += 8) out += '        ' + edge.slice(i, i + 8).map(v => '0x' + v.toString(16).padStart(3, '0')).join(', ') + ',\n';
out += '    ];\n\n    public static readonly sbyte[] TriTable =\n    [\n';
for (const r of rows) out += '        ' + r.join(', ') + ',\n';
out += '    ];\n}\n';
fs.writeFileSync(process.argv[3], out);
console.log('ok', edge.length, rows.length);
